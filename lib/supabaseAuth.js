import * as Linking from 'expo-linking';
import * as WebBrowser from 'expo-web-browser';
import { Platform } from 'react-native';
import { isSupabaseConfigured, supabase } from '../supabase';

// Complete any pending browser sessions on mobile
if (Platform.OS !== 'web') {
  WebBrowser.maybeCompleteAuthSession();
}

/**
 * Parses query and hash fragments from OAuth redirect URLs.
 */
export function parseAuthUrl(url) {
  const params = {};
  if (!url) return params;

  // Supabase OAuth returns tokens in either the hash fragment (#) or search query (?)
  const hashIdx = url.indexOf('#');
  const queryIdx = url.indexOf('?');

  const fragment =
    hashIdx !== -1
      ? url.substring(hashIdx + 1)
      : queryIdx !== -1
      ? url.substring(queryIdx + 1)
      : '';

  fragment.split('&').forEach((part) => {
    const [rawKey, rawVal] = part.split('=');
    if (rawKey && rawVal) {
      params[decodeURIComponent(rawKey)] = decodeURIComponent(rawVal);
    }
  });

  return params;
}

/**
 * Initiates Google / Gmail OAuth Sign-In via Supabase.
 * Works seamlessly across Android, iOS, and Web.
 */
export async function signInWithGoogle(desiredRole = 'user') {
  if (!isSupabaseConfigured()) {
    throw new Error(
      'Supabase is not configured yet. Please update SUPABASE_URL and SUPABASE_ANON_KEY in supabase.js or your .env file.'
    );
  }

  try {
    // Generate the app deep link redirect URL
    const redirectUrl = Linking.createURL('auth/callback');

    if (Platform.OS === 'web') {
      // On web, direct browser redirection
      const { data, error } = await supabase.auth.signInWithOAuth({
        provider: 'google',
        options: {
          redirectTo: typeof window !== 'undefined' ? window.location.origin : redirectUrl,
          queryParams: {
            access_type: 'offline',
            prompt: 'consent',
          },
        },
      });

      if (error) throw error;
      return { url: data?.url };
    }

    // On Native (Android / iOS): Open browser in-app session
    const { data, error } = await supabase.auth.signInWithOAuth({
      provider: 'google',
      options: {
        redirectTo: redirectUrl,
        skipBrowserRedirect: true,
        queryParams: {
          access_type: 'offline',
          prompt: 'select_account',
        },
      },
    });

    if (error) throw error;
    if (!data?.url) throw new Error('No authentication URL was generated by Supabase.');

    const authResult = await WebBrowser.openAuthSessionAsync(data.url, redirectUrl);

    if (authResult.type === 'success' && authResult.url) {
      const parsed = parseAuthUrl(authResult.url);

      if (parsed.access_token && parsed.refresh_token) {
        const { data: sessionData, error: sessionError } =
          await supabase.auth.setSession({
            access_token: parsed.access_token,
            refresh_token: parsed.refresh_token,
          });

        if (sessionError) throw sessionError;

        const user = sessionData.user;
        const profile = await syncUserProfile(user, desiredRole);

        return {
          user,
          session: sessionData.session,
          role: profile.role || desiredRole,
        };
      }
    }

    if (authResult.type === 'cancel' || authResult.type === 'dismiss') {
      return null;
    }

    return null;
  } catch (err) {
    console.error('signInWithGoogle error:', err);
    throw err;
  }
}

/**
 * Signs in using Email and Password via Supabase Auth.
 */
export async function signInWithSupabaseEmail(email, password) {
  if (!isSupabaseConfigured()) {
    throw new Error('Supabase is not configured yet. Please configure supabase.js.');
  }

  const { data, error } = await supabase.auth.signInWithPassword({
    email: email.trim(),
    password,
  });

  if (error) throw error;

  const profile = await getUserProfile(data.user.id);
  return {
    user: data.user,
    session: data.session,
    role: profile?.role || 'user',
  };
}

/**
 * Creates a new account with Email, Password, and Role in Supabase Auth & Profiles.
 */
export async function signUpWithSupabaseEmail(email, password, role = 'user') {
  if (!isSupabaseConfigured()) {
    throw new Error('Supabase is not configured yet. Please configure supabase.js.');
  }

  const { data, error } = await supabase.auth.signUp({
    email: email.trim(),
    password,
    options: {
      data: {
        role,
      },
    },
  });

  if (error) throw error;

  if (data?.user) {
    await syncUserProfile(data.user, role);
  }

  return {
    user: data.user,
    session: data.session,
    role,
  };
}

/**
 * Fetches user profile record from the 'profiles' table.
 */
export async function getUserProfile(userId) {
  if (!userId || !isSupabaseConfigured()) return null;

  try {
    const { data, error } = await supabase
      .from('profiles')
      .select('*')
      .eq('id', userId)
      .maybeSingle();

    if (error) {
      console.warn('Could not read user profile from Supabase:', error.message);
      return null;
    }

    return data;
  } catch (e) {
    console.warn('getUserProfile error:', e);
    return null;
  }
}

/**
 * Ensures a user record exists in 'profiles' with an assigned role.
 */
export async function syncUserProfile(user, fallbackRole = 'user') {
  if (!user?.id || !isSupabaseConfigured()) {
    return { role: fallbackRole };
  }

  try {
    const existing = await getUserProfile(user.id);

    if (existing) {
      return existing;
    }

    // Insert new profile
    const newProfile = {
      id: user.id,
      email: user.email,
      role: fallbackRole,
      created_at: new Date().toISOString(),
      updated_at: new Date().toISOString(),
    };

    const { data, error } = await supabase
      .from('profiles')
      .upsert(newProfile, { onConflict: 'id' })
      .select()
      .maybeSingle();

    if (error) {
      console.warn('Could not insert Supabase user profile:', error.message);
      return newProfile;
    }

    return data || newProfile;
  } catch (err) {
    console.warn('syncUserProfile error:', err);
    return { role: fallbackRole };
  }
}

/**
 * Logs out the current user session from Supabase.
 */
export async function signOutSupabase() {
  if (isSupabaseConfigured()) {
    try {
      await supabase.auth.signOut();
    } catch (e) {
      console.warn('Supabase signOut error:', e);
    }
  }
}
